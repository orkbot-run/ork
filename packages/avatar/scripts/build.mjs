import { mkdir, readFile, writeFile } from "node:fs/promises";

// This local bundle also works from file://, where browsers block module imports.
const art = await readFile(new URL("../src/art.mjs", import.meta.url), "utf8");
const renderer = await readFile(new URL("../src/renderer.mjs", import.meta.url), "utf8");
const generator = await readFile(new URL("../src/generator.mjs", import.meta.url), "utf8");
const declarations = (source) =>
  source
    .replace(/^import[\s\S]*?from ["'][^"']+["'];\n/gm, "")
    .replace(/^export (?=(?:function|const|class)\b)/gm, "");
const body = [art, renderer, generator].map(declarations).join("\n");
const bundle = `// Generated by scripts/build.mjs. Edit src/ instead.\n(() => {\n"use strict";\n${body}\nglobalThis.OrkAvatar = Object.freeze({VERSION, MAX_ENCODED_AVATAR_STRING_LENGTH, PARAMETER_RULES, CLASSIC_PARAMETERS, ValidationError, encodeAvatar, decodeAvatar, renderAvatar, avatarFromString, createAvatar});\n})();\n`;
await mkdir(new URL("../dist/", import.meta.url), { recursive: true });
await writeFile(new URL("../dist/ork-avatar.js", import.meta.url), bundle);
console.log("Built dist/ork-avatar.js");
