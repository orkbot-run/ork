import { newClientId } from "./client-id.js";

/** A cosmetic, portable generator seed. It never proves account ownership. */
export function isPersonalOrkId(value: unknown): value is string {
  return (
    typeof value === "string" &&
    /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/.test(value)
  );
}

export function createPersonalOrkId(): string {
  return newClientId();
}
